import assert from 'node:assert/strict'
import { createServer } from 'vite'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const server = await createServer({ define: { 'import.meta.env.VITE_GEOAPIFY_API_KEY': JSON.stringify('test-fixture') }, server: { host: '127.0.0.1', port: 5193, strictPort: true } })
let browser
try {
  await server.listen()
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) })
  for (const mobile of [false, true]) {
    const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, timezoneId: 'Australia/Melbourne' })
    const page = await context.newPage()
    await page.addInitScript(() => {
      localStorage.setItem('heatsafe-onboarding-complete', 'true')
      localStorage.setItem('heatSafe.language', 'en')
      window.notificationRequests = 0
      Notification.requestPermission = () => { window.notificationRequests++; return Promise.resolve('denied') }
    })
    await page.route('https://api.geoapify.com/**', route => route.fulfill({ json: { results: [{ country_code: 'au', place_id: 'fixture-library', formatted: 'Demo Library, Melbourne', name: 'Demo Library', lat: -37.81, lon: 144.96 }] } }))
    await page.goto('http://127.0.0.1:5193/travel-planner')
    const destination = page.getByRole('combobox', { name: 'Destination', exact: true })
    const arrivalInput = page.getByLabel('Desired arrival date and time')
    const transport = page.getByLabel('Transportation', { exact: true })
    const generate = page.getByRole('button', { name: 'Generate travel recommendation', exact: true })
    const modal = page.getByRole('dialog', { name: 'Your travel recommendation', exact: true })
    const bell = page.locator('[data-reminder-bell]')
    const popover = page.getByRole('dialog', { name: 'Departure reminders', exact: true })
    const due = page.getByRole('dialog', { name: 'Time to leave for Demo Library', exact: true })
    const inputTime = seconds => page.evaluate(seconds => {
      const d = new Date(Date.now() + seconds * 1000)
      return new Date(d.getTime() - d.getTimezoneOffset() * 60000).toISOString().slice(0, 19).replace(/:00$/, '')
    }, seconds)
    const save = async seconds => {
      await transport.selectOption('DRIVE')
      await arrivalInput.fill(await inputTime(240 + seconds))
      await generate.click()
      await modal.getByRole('button', { name: 'Set departure reminder', exact: true }).click()
    }
    await destination.fill('Demo Library')
    await page.getByRole('listbox').getByRole('option').first().click()
    await arrivalInput.fill(await inputTime(60))
    await generate.click()
    await page.getByText('Choose a later arrival time so your recommended departure is still in the future.').waitFor()
    const arrival = await inputTime(3600)
    await arrivalInput.fill(arrival)
    for (const [method, label, minutes] of [['WALK', 'Walking', 12], ['TRANSIT', 'Public transport', 8], ['DRIVE', 'Driving', 4]]) {
      await transport.selectOption(method)
      await generate.click()
      await modal.waitFor()
      assert.ok((await modal.textContent()).includes(label))
      assert.ok((await modal.textContent()).includes(`Approximately ${minutes} minutes`))
      assert.ok((await modal.textContent()).includes('Demo Library'))
      const times = await modal.locator('time').evaluateAll(els => els.map(el => Date.parse(el.dateTime)))
      assert.equal(times[0] - times[1], minutes * 60000)
      await page.keyboard.press('Shift+Tab')
      assert.ok(await modal.evaluate(el => el.contains(document.activeElement)))
      await modal.getByRole('button', { name: 'Back to edit', exact: true }).click()
      assert.equal(await arrivalInput.inputValue(), arrival)
      assert.equal(await transport.inputValue(), method)
      assert.equal(await destination.inputValue(), 'Demo Library, Melbourne')
      assert.ok(await generate.evaluate(el => el === document.activeElement))
    }
    await generate.click()
    const departure = Date.parse(await modal.locator('section time').getAttribute('datetime'))
    await modal.getByRole('button', { name: 'Set departure reminder', exact: true }).click()
    await page.getByText('Departure reminder added to your notifications.', { exact: true }).waitFor()
    assert.equal(await modal.count(), 0)
    assert.equal(await arrivalInput.inputValue(), arrival)
    assert.match(await bell.getAttribute('aria-label'), /1 upcoming enabled/)
    await generate.click()
    await modal.getByRole('button', { name: 'Set departure reminder', exact: true }).click()
    await modal.getByText('A reminder already exists for this travel plan and departure time.').waitFor()
    await page.keyboard.press('Escape')
    const before = await page.locator('main').boundingBox()
    await bell.click()
    assert.equal(Date.parse(await popover.locator('time').getAttribute('datetime')), departure)
    assert.equal((await page.locator('main').boundingBox()).height, before.height)
    const box = await popover.boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= (mobile ? 390 : 1440))
    const toggle = popover.getByRole('switch')
    await toggle.press('Space')
    assert.equal(await toggle.getAttribute('aria-checked'), 'false')
    assert.match(await bell.getAttribute('aria-label'), /0 upcoming enabled/)
    await page.reload()
    await bell.click()
    assert.equal(await toggle.getAttribute('aria-checked'), 'false')
    assert.equal(Date.parse(await popover.locator('time').getAttribute('datetime')), departure)
    await toggle.click()
    assert.match(await bell.getAttribute('aria-label'), /1 upcoming enabled/)
    await popover.getByRole('button', { name: 'Delete reminder', exact: true }).click()
    await popover.getByText('No departure reminders', { exact: true }).waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await destination.inputValue(), 'Demo Library, Melbourne')
    await save(5)
    await bell.click()
    await toggle.click()
    await page.keyboard.press('Escape')
    await page.waitForTimeout(5500)
    assert.equal(await due.count(), 0, 'disabled reminder never triggers')
    await bell.click()
    await popover.getByRole('button', { name: 'Delete reminder', exact: true }).click()
    await page.keyboard.press('Escape')
    await save(5)
    await bell.click()
    await popover.getByRole('button', { name: 'Delete reminder', exact: true }).click()
    await page.keyboard.press('Escape')
    await page.waitForTimeout(5500)
    assert.equal(await due.count(), 0, 'deleted reminder never triggers')
    await save(7)
    await bell.click()
    await toggle.click()
    await toggle.click()
    await page.keyboard.press('Escape')
    await due.waitFor({ timeout: 10000 })
    await due.getByRole('button', { name: 'View travel plan', exact: true }).click()
    await modal.waitFor()
    assert.ok((await modal.textContent()).includes('Demo Library'))
    await page.keyboard.press('Escape')
    await page.reload()
    await generate.waitFor()
    await page.waitForTimeout(1500)
    assert.equal(await due.count(), 0, 'completed reminder does not repeat')
    assert.equal(await page.locator('main section time').count(), 0, 'recommendation is not inline')
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    assert.equal(await page.evaluate(() => window.notificationRequests), 0)
    await context.close()
    console.log(`PASS ${mobile ? 'mobile' : 'desktop'}: arrival form, all transport calculations, back/edit, exact reminder time, duplicates, switches, persistence, delete, near-future alert once`)
  }
} finally { await browser?.close(); await server.close() }
